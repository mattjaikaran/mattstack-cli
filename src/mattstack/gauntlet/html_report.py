def _header(project_path: Path, result: RunResult) -> str:
    """Build the page header."""
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    return f"""<header>
    <div class="container">
        <h1>Audit Report &mdash; {escape(project_path.name)}</h1>
        <p>{escape(str(project_path))} &middot; {escape(now)} &middot; \
tier {escape(result.tier or "unknown")}</p>
    </div>
</header>"""


def _summary(result: RunResult) -> str:
    """Build the summary cards."""
    return f"""<div class="container">
    <div class="cards">
        <div class="card total">
            <div class="label">Total Findings</div>
            <div class="value">{len(result.findings)}</div>
        </div>
        <div class="card error">
            <div class="label">Errors</div>
            <div class="value">{result.error_count}</div>
        </div>
        <div class="card warning">
            <div class="label">Warnings</div>
            <div class="value">{result.warning_count}</div>
        </div>
        <div class="card info">
            <div class="label">Info</div>
            <div class="value">{result.info_count}</div>
        </div>
    </div>"""


def _filters() -> str:
    """Build the filter buttons."""
    return """<div class="filters">
        <button class="active" data-filter="all">All</button>
        <button data-filter="error">Errors</button>
        <button data-filter="warning">Warnings</button>
        <button data-filter="info">Info</button>
    </div>"""


def _build_findings_rows(findings: list[Finding]) -> str:
    """Build HTML table rows for findings."""
    rows: list[str] = []
    for finding in sorted(findings, key=lambda f: (f.severity.value, f.check, f.location)):
        marker = ' <span class="blocking">blocking</span>' if finding.blocking else ""
        rows.append(
            f'<tr data-severity="{escape(finding.severity.value)}" '
            f'data-category="{escape(finding.category)}">'
            f'<td><span class="badge badge-{escape(finding.severity.value)}">'
            f"{escape(finding.severity.value)}</span></td>"
            f"<td>{escape(finding.category)}</td>"
            f"<td>{escape(finding.location)}</td>"
            f"<td>{escape(finding.title)}{marker}</td>"
            f"<td>{escape(finding.suggested_fix or '')}</td>"
            f"</tr>"
        )
    return "\n".join(rows)


def _table(rows: str) -> str:
    """Build the findings table."""
    if not rows:
        return '<div class="empty-state"><p>No findings. Project looks clean!</p></div></div>'
    return f"""<table id="findings-table">
        <thead>
            <tr>
                <th data-col="0">Severity</th>
                <th data-col="1">Category</th>
                <th data-col="2">Location</th>
                <th data-col="3">Message</th>
                <th data-col="4">Suggestion</th>
            </tr>
        </thead>
        <tbody>
            {rows}
        </tbody>
    </table>
</div>"""


def _skipped_checks(result: RunResult) -> str:
    """Build the note about checks that did not run."""
    skipped = [c for c in result.checks if c.status == CheckStatus.SKIP]
    if not skipped:
        return ""
    items = "".join(
        f"<li>{escape(c.check)}: {escape(c.note or 'tool not found')}</li>" for c in skipped
    )
    return f'<div class="container"><div class="skipped">Skipped checks<ul>{items}</ul></div></div>'


def _js() -> str:
    """Return inline JavaScript for filtering and sorting."""
    return """
    (function() {
        var buttons = document.querySelectorAll('.filters button');
        buttons.forEach(function(btn) {
            btn.addEventListener('click', function() {
                buttons.forEach(function(b) { b.classList.remove('active'); });
                btn.classList.add('active');
                var filter = btn.getAttribute('data-filter');
                var rows = document.querySelectorAll('#findings-table tbody tr');
                rows.forEach(function(row) {
                    if (filter === 'all' || row.getAttribute('data-severity') === filter) {
                        row.style.display = '';
                    } else {
                        row.style.display = 'none';
                    }
                });
            });
        });

        var headers = document.querySelectorAll('#findings-table th');
        var sortState = {};
        headers.forEach(function(th) {
            th.addEventListener('click', function() {
                var col = parseInt(th.getAttribute('data-col'));
                var tbody = document.querySelector('#findings-table tbody');
                if (!tbody) return;
                var rows = Array.from(tbody.querySelectorAll('tr'));
                var asc = sortState[col] !== 'asc';
                sortState = {};
                sortState[col] = asc ? 'asc' : 'desc';
                headers.forEach(function(h) { h.classList.remove('sort-asc', 'sort-desc'); });
                th.classList.add(asc ? 'sort-asc' : 'sort-desc');
                rows.sort(function(a, b) {
                    var aText = a.children[col].textContent.toLowerCase();
                    var bText = b.children[col].textContent.toLowerCase();
                    if (aText < bText) return asc ? -1 : 1;
                    if (aText > bText) return asc ? 1 : -1;
                    return 0;
                });
                rows.forEach(function(row) { tbody.appendChild(row); });
            });
        });
    })();
    """
