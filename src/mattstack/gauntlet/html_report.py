"""Standalone HTML dashboard for a Gauntlet run.

Kept separate from `report.py` so both modules stay well inside the 400-line
file-length gate.
"""

from __future__ import annotations

from datetime import datetime
from html import escape
from pathlib import Path

from mattstack.gauntlet.models import CheckStatus, Finding, RunResult


def generate_html_report(result: RunResult, project_path: Path) -> str:
    """Generate a standalone HTML dashboard for the run."""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>Audit Report — {escape(project_path.name)}</title>
    <style>{_css()}</style>
</head>
<body>
    {_header(project_path, result)}
    {_summary(result)}
    {_filters()}
    {_table(_build_findings_rows(result.findings))}
    {_skipped_checks(result)}
    <footer>Generated by mattstack audit. Checks by Gauntlet \
{escape(result.gauntlet_version or "unknown")}.</footer>
    <script>{_js()}</script>
</body>
</html>"""


